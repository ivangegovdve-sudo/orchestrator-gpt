// One-shot: extract the PLATFORMS array literal from scripts/llm-db-source.html
// (the retired /web/llm-db/ page, kept as data source of truth) into
// web/library/platforms-data.js as window.LIBRARY_PLATFORMS. Single edit point
// remains the PLATFORMS array in llm-db-source.html; re-run this after changing it.
const fs = require("fs");
const path = require("path");
const root = path.join(__dirname, "..");
const src = fs.readFileSync(path.join(root, "scripts/llm-db-source.html"), "utf8");
const start = src.indexOf("const PLATFORMS = [");
if (start === -1) throw new Error("PLATFORMS array not found");
const open = src.indexOf("[", start);
// Walk brackets to find the matching close (data has no brackets in strings
// except none — but be safe and count, ignoring bracket chars inside strings).
let depth = 0, i = open, inStr = false, q = "", end = -1;
for (; i < src.length; i++) {
  const ch = src[i];
  if (inStr) {
    if (ch === "\\") { i++; continue; }
    if (ch === q) inStr = false;
    continue;
  }
  if (ch === '"' || ch === "'" || ch === "`") { inStr = true; q = ch; continue; }
  if (ch === "[") depth++;
  else if (ch === "]") { depth--; if (depth === 0) { end = i; break; } }
}
if (end === -1) throw new Error("Could not find end of PLATFORMS array");
const arrayLiteral = src.slice(open, end + 1);
// Validate it parses as JS by evaluating in a sandboxed Function.
const data = new Function("return " + arrayLiteral + ";")();
if (!Array.isArray(data) || !data.length) throw new Error("Extraction produced no data");
const out =
  "// AUTO-GENERATED by scripts/extract-platforms.cjs from scripts/llm-db-source.html.\n" +
  "// Do not edit by hand — edit the PLATFORMS array in llm-db-source.html and re-run the script.\n" +
  "window.LIBRARY_PLATFORMS = " + JSON.stringify(data, null, 0) + ";\n";
fs.writeFileSync(path.join(root, "web/library/platforms-data.js"), out);
console.log("Wrote web/library/platforms-data.js with " + data.length + " platforms");
